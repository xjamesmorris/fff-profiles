"""Each test builds a throwaway repo (profiles/) and PrusaSlicer config dir in temp dirs."""

import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))

import sync  # noqa: E402

PROFILE = "profiles/Acme/filament/PLA__PrusaCOREOne_Prusaslicer.ini"
REPO_TEXT = """# hand-written header comment
[filament:Acme PLA]
filament_vendor = Acme
inherits = Generic PLA @COREONE
temperature = 215
"""
LIVE_SAME = """# generated by PrusaSlicer 2.9.6 on 2026-10-18 at 08:00:00 UTC
filament_vendor = Acme
inherits = Generic PLA @COREONE
temperature = 215
"""


class SyncCase(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        base = Path(self.tmp.name)
        self.root = base / "repo"
        self.config = base / "PrusaSlicer"
        (self.config / "filament").mkdir(parents=True)
        self.write_repo(PROFILE, REPO_TEXT)

    def tearDown(self):
        self.tmp.cleanup()

    def write_repo(self, rel, text):
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def write_live(self, name, text, kind="filament"):
        p = self.config / kind / f"{name}.ini"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        return p

    def run_sync(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), \
                mock.patch.object(sync, "prusaslicer_running", return_value=False):
            sync.main(["--root", str(self.root), "--config-dir", str(self.config), *argv])
        return out.getvalue()

    def live(self, name):
        return (self.config / "filament" / f"{name}.ini").read_text(encoding="utf-8")

    def repo(self, rel=PROFILE):
        return (self.root / rel).read_text(encoding="utf-8")


class TestStatus(SyncCase):
    def test_same_ignores_comments(self):
        self.write_live("Acme PLA", LIVE_SAME)
        self.assertIn("1 same, 0 differ, 0 missing", self.run_sync("status"))

    def test_missing(self):
        out = self.run_sync("status")
        self.assertIn("missing in PrusaSlicer  [filament:Acme PLA]", out)

    def test_differs_lists_keys(self):
        self.write_live("Acme PLA", LIVE_SAME.replace("215", "220"))
        out = self.run_sync("status", "--diff")
        self.assertIn("keys: temperature", out)
        self.assertIn("+temperature = 220", out)

    def test_conflicting_copies_in_repo_rejected(self):
        self.write_repo("profiles/Acme/filament/Other__PrusaCOREOne_Prusaslicer.ini",
                        REPO_TEXT.replace("215", "230"))
        with self.assertRaises(SystemExit):
            self.run_sync("status")

    def test_unknown_target_rejected(self):
        with self.assertRaises(SystemExit):
            self.run_sync("status", "Nope")


class TestInstall(SyncCase):
    def test_install_writes_values_and_backs_up(self):
        self.write_live("Acme PLA", LIVE_SAME.replace("215", "220"))
        self.run_sync("install")
        text = self.live("Acme PLA")
        self.assertIn("temperature = 215", text)
        self.assertTrue(text.startswith("# installed by fff-profiles from " + PROFILE))
        self.assertNotIn("[filament:", text)
        backups = list((self.config / sync.BACKUP_DIR).rglob("Acme PLA.ini"))
        self.assertEqual(len(backups), 1)
        self.assertIn("temperature = 220", backups[0].read_text(encoding="utf-8"))

    def test_install_missing_preset(self):
        self.run_sync("install")
        self.assertIn("temperature = 215", self.live("Acme PLA"))

    def test_dry_run_changes_nothing(self):
        out = self.run_sync("install", "-n")
        self.assertIn("would install", out)
        self.assertFalse((self.config / "filament" / "Acme PLA.ini").exists())

    def test_refuses_while_prusaslicer_runs(self):
        with mock.patch.object(sync, "prusaslicer_running", return_value=True):
            with self.assertRaises(SystemExit):
                sync.main(["--root", str(self.root), "--config-dir", str(self.config),
                           "install"])

    def test_target_by_file_path(self):
        self.run_sync("install", str(self.root / PROFILE))
        self.assertTrue((self.config / "filament" / "Acme PLA.ini").exists())


class TestPull(SyncCase):
    def test_pull_updates_section_and_keeps_header(self):
        self.write_live("Acme PLA", LIVE_SAME.replace("215", "220"))
        self.run_sync("pull")
        text = self.repo()
        self.assertTrue(text.startswith("# hand-written header comment\n[filament:Acme PLA]\n"))
        self.assertIn("temperature = 220", text)
        self.assertNotIn("generated by PrusaSlicer", text)

    def test_pull_leaves_other_sections(self):
        self.write_repo(PROFILE, REPO_TEXT + "\n[filament:Acme Base]\ntemperature = 200\n")
        self.write_live("Acme PLA", LIVE_SAME.replace("215", "220"))
        self.write_live("Acme Base", "temperature = 200\n")
        self.run_sync("pull")
        text = self.repo()
        self.assertIn("temperature = 220\n\n[filament:Acme Base]\ntemperature = 200\n", text)

    def test_pull_skips_missing(self):
        out = self.run_sync("pull")
        self.assertIn("skip", out)
        self.assertEqual(self.repo(), REPO_TEXT)

    def test_round_trip_is_stable(self):
        self.run_sync("install")
        self.run_sync("pull")
        self.assertEqual(self.repo(), REPO_TEXT)


class TestAdd(SyncCase):
    def test_add_includes_user_parent(self):
        self.write_live("Acme PETG", "inherits = Acme PETG Base\ntemperature = 240\n")
        self.write_live("Acme PETG Base", "inherits = Generic PETG @COREONE\nbed_temperature = 80\n")
        out = self.run_sync("add", "Acme PETG", "--vendor", "Acme", "--base", "PETG")
        text = self.repo("profiles/Acme/filament/PETG__PrusaCOREOne_Prusaslicer.ini")
        self.assertLess(text.index("[filament:Acme PETG Base]"), text.index("[filament:Acme PETG]"))
        self.assertIn("Generic PETG @COREONE", out)   # system parent noted

    def test_add_refuses_existing_file(self):
        self.write_live("Acme PLA", LIVE_SAME)
        with self.assertRaises(SystemExit):
            self.run_sync("add", "Acme PLA", "--vendor", "Acme", "--base", "PLA")

    def test_add_unknown_preset(self):
        with self.assertRaises(SystemExit):
            self.run_sync("add", "Nope", "--vendor", "Acme")


if __name__ == "__main__":
    unittest.main()
