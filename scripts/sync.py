"""
The repo's profiles/ tree is the source of truth. This tool compares it with
PrusaSlicer's user preset directory and copies presets from PrusaSlicer into the repo:

  status          which repo presets differ from (or are missing in) PrusaSlicer
  pull            PrusaSlicer -> repo, for presets already in the repo
  add NAME ...    bring a new PrusaSlicer preset (and any user-preset parents) into
                  the repo once; afterwards use pull

It never writes to PrusaSlicer's directory, so the author's working presets there are
never changed. To load a repo profile into PrusaSlicer, use File > Import > Import
Config Bundle (author's decision, 2026-10-19).

A repo profile is a small config bundle: `[filament:Name]` followed by `key = value`
lines. PrusaSlicer keeps the same lines in <config>/filament/Name.ini, under a
`# generated by PrusaSlicer …` comment. Comparisons ignore comment and blank lines.

Scope: like extract.py, this tool only copies preset lines verbatim. It never edits,
tunes, or flattens any technical values — that stays with the human author.

Usage:
  python3 scripts/sync.py status [--diff] [PRESET|FILE ...]
  python3 scripts/sync.py pull [-n] [PRESET|FILE ...]
  python3 scripts/sync.py add "Preset Name" --vendor V [--base B] [--kind filament]

PRESET is an exact preset name, FILE a repo profile path; with neither, every repo
profile is used. The PrusaSlicer configuration directory is found automatically
(macOS, Linux, Windows); override it with --config-dir or $PRUSASLICER_CONFIG_DIR.
"""

from __future__ import annotations

import argparse
import difflib
import os
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import extract  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
KINDS = ("filament", "print", "printer")   # section kind == PrusaSlicer subdirectory


@dataclass
class RepoPreset:
    kind: str
    name: str
    body: list[str]     # verbatim lines from the repo file
    files: list[Path]   # every repo file that carries this preset


def default_config_dir() -> Path:
    if os.environ.get("PRUSASLICER_CONFIG_DIR"):
        return Path(os.environ["PRUSASLICER_CONFIG_DIR"]).expanduser()
    home = Path.home()
    if sys.platform == "darwin":
        return home / "Library" / "Application Support" / "PrusaSlicer"
    if sys.platform.startswith("win"):
        return Path(os.environ.get("APPDATA", home)) / "PrusaSlicer"
    for p in (home / ".config" / "PrusaSlicer", home / ".PrusaSlicer"):
        if p.exists():
            return p
    return home / ".config" / "PrusaSlicer"


def values(lines: list[str]) -> list[str]:
    """The setting lines that matter for comparison: no comments, no blanks."""
    return [l.rstrip() for l in lines if l.strip() and not l.lstrip().startswith("#")]


def live_path(config_dir: Path, kind: str, name: str) -> Path:
    return config_dir / kind / f"{name}.ini"


def read_live(path: Path) -> list[str] | None:
    if not path.exists():
        return None
    return values(path.read_text(encoding="utf-8").splitlines())


def repo_files(root: Path) -> list[Path]:
    return sorted((root / "profiles").glob("*/*/*.ini"))


def load_repo(root: Path) -> dict[tuple[str, str], RepoPreset]:
    """Every preset in profiles/, keyed by (kind, name). A preset shared by several
    files (a common user parent) is listed once, with all its files."""
    presets: dict[tuple[str, str], RepoPreset] = {}
    for f in repo_files(root):
        for s in extract.parse_bundle(f.read_text(encoding="utf-8")):
            if s.kind not in KINDS or not s.name:
                continue
            p = presets.get((s.kind, s.name))
            if p is None:
                presets[(s.kind, s.name)] = RepoPreset(s.kind, s.name, s.body, [f])
            else:
                if values(p.body) != values(s.body):
                    raise SystemExit(f"error: [{s.kind}:{s.name}] differs between "
                                     f"{rel(p.files[0], root)} and {rel(f, root)}")
                p.files.append(f)
    return presets


def rel(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root.resolve()))
    except ValueError:
        return str(path)


def select(presets: dict[tuple[str, str], RepoPreset], targets: list[str],
           root: Path) -> list[RepoPreset]:
    """Presets named by targets (preset names or repo file paths); all when empty."""
    if not targets:
        return list(presets.values())
    chosen: dict[tuple[str, str], RepoPreset] = {}
    for t in targets:
        path = Path(t)
        if not path.is_absolute():
            path = Path.cwd() / path
        if path.suffix == ".ini" and path.exists():
            hits = [p for p in presets.values()
                    if any(f.resolve() == path.resolve() for f in p.files)]
        else:
            hits = [p for p in presets.values() if p.name == t]
        if not hits:
            raise SystemExit(f"error: no repo preset or profile file matches {t!r}")
        for p in hits:
            chosen[(p.kind, p.name)] = p
    return list(chosen.values())


def changed_keys(a: list[str], b: list[str]) -> list[str]:
    def kv(lines):
        return dict(l.split("=", 1) if "=" in l else (l, "") for l in lines)
    da, db = kv(a), kv(b)
    return sorted(k.strip() for k in set(da) | set(db) if da.get(k) != db.get(k))


def compare(p: RepoPreset, config_dir: Path) -> tuple[str, list[str] | None]:
    live = read_live(live_path(config_dir, p.kind, p.name))
    if live is None:
        return "missing", None
    return ("same" if live == values(p.body) else "differs"), live


def cmd_status(selected, config_dir, root, show_diff) -> int:
    counts = {"same": 0, "differs": 0, "missing": 0}
    for p in sorted(selected, key=lambda p: (p.kind, p.name)):
        state, live = compare(p, config_dir)
        counts[state] += 1
        if state == "same":
            continue
        where = rel(p.files[0], root)
        if state == "missing":
            print(f"missing in PrusaSlicer  [{p.kind}:{p.name}]  ({where})")
            continue
        newer = "PrusaSlicer" if (live_path(config_dir, p.kind, p.name).stat().st_mtime
                                  > p.files[0].stat().st_mtime) else "repo"
        print(f"differs ({newer} newer)  [{p.kind}:{p.name}]  ({where})")
        print(f"    keys: {', '.join(changed_keys(values(p.body), live))}")
        if show_diff:
            for line in difflib.unified_diff(values(p.body), live, "repo", "PrusaSlicer",
                                             lineterm="", n=0):
                print("    " + line)
    print(f"status: {counts['same']} same, {counts['differs']} differ, "
          f"{counts['missing']} missing in PrusaSlicer ({config_dir})")
    return 0


def replace_section(text: str, kind: str, name: str, body: list[str]) -> str:
    """Swap one section's lines in a repo file, leaving everything else as it was."""
    lines = text.splitlines()
    header = f"[{kind}:{name}]"
    start = lines.index(header)
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("[")),
               len(lines))
    tail = [""] if end < len(lines) else []
    return "\n".join(lines[:start + 1] + body + tail + lines[end:]) + "\n"


def cmd_pull(selected, config_dir, root, dry_run) -> int:
    n = 0
    for p in sorted(selected, key=lambda p: (p.kind, p.name)):
        state, live = compare(p, config_dir)
        if state == "missing":
            print(f"skip  [{p.kind}:{p.name}]  (not in PrusaSlicer)")
            continue
        if state == "same":
            continue
        n += 1
        for f in p.files:
            print(f"{'would update' if dry_run else 'update'}  {rel(f, root)}  "
                  f"[{p.kind}:{p.name}]  keys: {', '.join(changed_keys(values(p.body), live))}")
            if not dry_run:
                f.write_text(replace_section(f.read_text(encoding="utf-8"),
                                             p.kind, p.name, live), encoding="utf-8")
    if not n:
        print("nothing to pull: the repo already matches PrusaSlicer")
    elif not dry_run:
        print("review with: git diff profiles/")
    return 0


def load_live_sections(config_dir: Path, kind: str) -> list[extract.Section]:
    return [extract.Section(kind, f.stem, values(f.read_text(encoding="utf-8").splitlines()))
            for f in sorted((config_dir / kind).glob("*.ini"))]


def cmd_add(args, config_dir, root) -> int:
    sections = load_live_sections(config_dir, args.kind)
    try:
        emitted, notes = extract.collect(sections, [(args.kind, args.name)])
    except KeyError:
        raise SystemExit(f"error: no {args.kind} preset {args.name!r} in {config_dir / args.kind}")
    base = args.base or extract.derive_base(args.name, args.vendor)
    category = "filament" if args.kind == "filament" else "process"
    path = root / extract.output_path("profiles", args.vendor, category,
                                      extract.build_filename(base, args.printer_label,
                                                             args.slicer_label))
    if path.exists() and not args.force:
        raise SystemExit(f"error: {rel(path, root)} already exists; use pull to update it")
    existing = load_repo(root)
    for s in emitted:
        if (s.kind, s.name) in existing and s.name != args.name:
            print(f"  note: parent [{s.kind}:{s.name}] is also in "
                  f"{rel(existing[(s.kind, s.name)].files[0], root)}")
    extract.write_output(emitted, notes, path)
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config-dir", type=Path, help="PrusaSlicer configuration directory")
    ap.add_argument("--root", type=Path, default=REPO, help="repository root")
    sub = ap.add_subparsers(dest="cmd", required=True)

    st = sub.add_parser("status", help="show presets that differ between repo and PrusaSlicer")
    st.add_argument("--diff", action="store_true", help="print the differing lines")
    st.add_argument("targets", nargs="*")

    pl = sub.add_parser("pull", help="copy PrusaSlicer presets back into the repo")
    pl.add_argument("-n", "--dry-run", action="store_true")
    pl.add_argument("targets", nargs="*")

    ad = sub.add_parser("add", help="bring a new PrusaSlicer preset into the repo")
    ad.add_argument("name", help="exact preset name")
    ad.add_argument("--vendor", required=True, help="vendor directory under profiles/")
    ad.add_argument("--base", help="filename base (derived from the name if omitted)")
    ad.add_argument("--kind", choices=KINDS, default="filament")
    ad.add_argument("--printer-label", default=extract.DEFAULT_PRINTER_LABEL)
    ad.add_argument("--slicer-label", default=extract.DEFAULT_SLICER_LABEL)
    ad.add_argument("--force", action="store_true", help="overwrite an existing repo file")

    args = ap.parse_args(argv)
    config_dir = (args.config_dir or default_config_dir()).expanduser()
    root = args.root
    if not (config_dir / "filament").is_dir() and args.cmd != "status":
        raise SystemExit(f"error: no PrusaSlicer configuration at {config_dir}")

    if args.cmd == "add":
        return cmd_add(args, config_dir, root)
    selected = select(load_repo(root), args.targets, root)
    if args.cmd == "status":
        return cmd_status(selected, config_dir, root, args.diff)
    return cmd_pull(selected, config_dir, root, args.dry_run)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
